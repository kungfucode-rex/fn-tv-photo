package store

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
)

// Device is an album end that has registered itself.
type Device struct {
	ID         string
	TokenHash  string
	OwnerToken string // only ever returned once, at issuance
	Name       string
	CreatedAt  int64
	LastSeenAt int64
}

// deviceSchema is applied alongside the main schema. It is separate here only
// because it reads better next to the code that uses it; migrate runs both.
const deviceSchema = `
CREATE TABLE IF NOT EXISTS devices (
  id            TEXT PRIMARY KEY,
  token_hash    TEXT NOT NULL,
  owner_token_hash TEXT,
  name          TEXT,
  created_at    INTEGER NOT NULL,
  last_seen_at  INTEGER NOT NULL
);
`

// IssueDevice registers a new album end and returns its token. The token itself
// is generated by the caller; only its hash is stored, so a leaked database
// cannot be used to register photos (docs/tuping-design.md §5, §7).
func (s *Store) IssueDevice(ctx context.Context, id, token, ownerToken, name string) error {
	now := s.nowMS()
	_, err := s.db.ExecContext(ctx, `
		INSERT INTO devices (id, token_hash, owner_token_hash, name, created_at, last_seen_at)
		VALUES (?,?,?,?,?,?)
		ON CONFLICT(id) DO UPDATE SET
			token_hash = excluded.token_hash,
			owner_token_hash = excluded.owner_token_hash,
			name = excluded.name,
			last_seen_at = excluded.last_seen_at`,
		id,
		HashToken(deviceSecret, token),
		nullableString(HashToken(deviceSecret, ownerToken)),
		nullableString(name),
		now, now)
	if err != nil {
		return fmt.Errorf("store: issue device: %w", err)
	}
	return nil
}

// deviceSecret is the salt the device token is hashed with. The store has its own
// so that a token issued by one deployment cannot be replayed against another
// that happens to hold the same secret for signed URLs.
const deviceSecret = "tuping/device"

// AuthenticateDevice checks a device id and token pair.
func (s *Store) AuthenticateDevice(ctx context.Context, id, token string) (bool, error) {
	if id == "" || token == "" {
		return false, nil
	}
	var stored string
	err := s.db.QueryRowContext(ctx, `SELECT token_hash FROM devices WHERE id=?`, id).Scan(&stored)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("store: authenticate device: %w", err)
	}
	if stored != HashToken(deviceSecret, token) {
		return false, nil
	}
	_, _ = s.db.ExecContext(ctx, `UPDATE devices SET last_seen_at=? WHERE id=?`, s.nowMS(), id)
	return true, nil
}

// DeviceExists reports whether an id has been issued.
func (s *Store) DeviceExists(ctx context.Context, id string) (bool, error) {
	var one int
	err := s.db.QueryRowContext(ctx, `SELECT 1 FROM devices WHERE id=?`, id).Scan(&one)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("store: device exists: %w", err)
	}
	return true, nil
}
